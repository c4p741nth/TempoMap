    public const string Thai = """
        เส้นแดง = BPM / จุดเริ่มกริดจังหวะ • เส้นเขียว = SV / Kiai / เสียงประกอบ
        เลือกแถวก่อนใช้เครื่องมือ กด Ctrl+Z เพื่อย้อนการแก้แต่ละขั้น

        Auto-time
        วิเคราะห์ทั้งเพลง แล้วแสดง BPM และ Offset ในแถวเดิม กด Apply เมื่อพร้อม เช่น เพลงอิเล็กทรอนิกส์ BPM คงที่ที่ยังไม่มี timing
        ช่อง BPM ว่าง = หาอัตโนมัติ, ตัวเลขที่พิมพ์เอง = ล็อก BPM ให้หาเฉพาะ offset แม้พิมพ์ทับผลเดิมแล้วกด Auto-time ซ้ำ
        เช่น แก้ผล 159.997 เป็น 160 แล้วกด Auto-time จะคง 160 และหา offset ใหม่ ล้างช่อง BPM เมื่อต้องการหา BPM อัตโนมัติอีกครั้ง
        หลังได้คำตอบ BPM เดียว: แก้ BPM/Offset ก่อน Apply ได้ เพลงหลาย BPM จะ Apply เป็นหลายเส้น

        Auto-time range (Ctrl+R)
        วิเคราะห์เฉพาะช่วงที่ไฮไลต์ด้วย Shift+ลาก หรือ Shift+ลูกศร แล้วแทนเส้นแดงในช่วงนั้นโดยคง timing นอกช่วงไว้
        เช่น ทั้งเพลง 143 BPM แต่ท่อน 49–55 วินาทีเปลี่ยนเป็น 180 BPM ให้เลือกเฉพาะท่อนนั้น

        Auto-time section
        วิเคราะห์จากเส้นแดงที่เลือกถึงเส้นแดงถัดไป แล้วแก้ BPM และตำแหน่งเริ่มของ section นั้น
        เช่น รู้ตำแหน่งท่อน verse/chorus แล้ว แต่ยังไม่รู้ BPM ของ chorus

        Fit offset
        คง BPM ของเส้นแดงที่เลือก แต่ขยับเวลาเริ่มให้กริดเข้ากับเสียงใน section
        เช่น รู้แน่ว่า 160 BPM แต่ทุกจังหวะเหลื่อมกลองประมาณ 20 ms ให้ใช้ Fit offset แทนการหา BPM ใหม่

        Check sections (Ctrl+K)
        ตรวจว่าแต่ละ section มีหลักฐาน onset รองรับกริดแค่ไหน แล้วทำเครื่องหมายช่วงที่ควรฟังซ้ำ ไม่แก้ timing เอง
        เช่น Auto-time ได้หลายร้อยเส้น ใช้ตรวจหาช่วงที่อาจล็อกครึ่งจังหวะหรือ BPM ผิดก่อนเปิดฟัง

        Multiply BPM
        กรอกตัวคูณแล้วกด Apply: 0.5 = หารสอง, 2 = คูณสอง, 1.5 = คูณหนึ่งครึ่ง ตำแหน่งเส้นแดงไม่เปลี่ยน
        เช่น ตรวจได้ 280 แต่ต้องการ 140 ให้ใช้ 0.5 กดซ้ำจะเป็น 70 และ 35; Undo ย้อนแต่ละการกดได้
        ใช้แก้ระดับจังหวะที่ผิดทั้งเท่าตัว ไม่ใช้แก้กริดที่ค่อย ๆ ลอย ซึ่งควรปรับ BPM ละเอียดแทน

        Snap to onsets
        ขยับเส้นแดงที่เลือกไปหาการโจมตีของเสียงใกล้ ๆ เช่น kick/snare โดยคง BPM
        เช่น ปักเส้น ramp ด้วยหูคลาดไม่กี่ ms แล้วให้ช่วยเก็บตำแหน่ง ใช้เฉพาะเส้นที่มีเสียงตีชัด ไม่เหมาะกับเสียงลากยาว

        BPM from spacing
        ใช้ระยะระหว่างเส้นแดงที่ปักไว้บนจังหวะต่อกันคำนวณ BPM และเชื่อมปลายช่วงให้ต่อกัน
        เช่น ปักเส้นบน kick ทุกจังหวะในท่อนเร่งสั้น ๆ แล้วเลือกเส้นเหล่านั้นเพื่อหา BPM ของแต่ละก้าว
        ระยะที่เป็น section ยาวหรือเส้นสุดท้ายอาจถูกคงไว้ จึงควรตรวจฟังหลังใช้

        Fill ramp (Ctrl+L)
        เลือกเส้นเริ่มและจบของการเร่ง/ชะลอ แล้วเติมเส้นแดงทุก beat ให้ BPM เปลี่ยนอย่างต่อเนื่อง
        เช่น เพลงค่อย ๆ เร่งจาก 120 เป็น 160 BPM; เลือกเส้นเริ่ม 120 และปลาย 160 ก่อน Fill ramp
        เป็นสมมติฐานว่า ramp เรียบ ถ้าเพลงมีช่วงคง BPM ระหว่างทาง ให้เลือก anchor ของช่วงนั้นเพิ่ม

        Bar line here
        กำหนดว่าเส้นแดงที่เลือกเป็น beat แรกของห้อง แล้วนับห้องต่อไปตาม Meter โดยตั้ง omit first barline ให้เส้นที่ไม่ใช่ต้นห้อง
        เช่น ramp มีเส้นแดงทุก beat แต่เส้นห้องโผล่ทุก beat ให้เลือก kick แรกของห้องจริงแล้วใช้ปุ่มนี้
        ไม่ได้ขยับเวลา ไม่ได้เปลี่ยน BPM และไม่ได้ใส่โน้ต

        SV และ Auto normalize SV
        ปิด (ค่าเริ่มต้น): SV ที่กรอก/นำเข้าอยู่เท่าเดิมแม้เพิ่มหรือแก้เส้นแดง ทำ SV ก่อนหรือหลัง timing ก็ได้
        เปิด: คง SV ที่เห็นขณะเปิดไว้เป็นฐาน เพิ่มเส้นชดเชยที่จำเป็น และปรับตามกริดแดงเมื่อ BPM เปลี่ยนภายหลัง
        ถ้าต้องการ SV ตัวเลขคงที่ให้ปิด ถ้าต้องการความเร็วที่ชดเชย BPM ให้เปิด การสลับโหมดย้อนด้วย Undo ได้
        Copy/Save ใช้เส้นที่เห็นอยู่ จึงไม่มีเมนู Copy normalized ซ้ำอีก; Ctrl+C คือแถวที่เลือก, Ctrl+Shift+C คือทั้งหมด

        Kiai
        เพิ่มเส้นเขียวด้วย Ctrl+G ตรงต้นท่อนที่ต้องการ แล้วติ๊ก Kiai เช่น ท่อน chorus
        เพิ่มเส้นเขียวอีกเส้นที่ท้าย chorus แล้วเอาติ๊กออกเพื่อจบ Kiai ไม่ต้องเปลี่ยน BPM หรือ SV
        ค่า Kiai อยู่ที่ timing point และมีผลจนกว่าจะมีจุด timing/effect ถัดไปกำหนดค่าใหม่ ควรตรวจช่วงใน osu! หลังวางเสร็จ


        Drift และ Beat model
        Drift 1/4/8/16/32 beats สร้างเส้นตามจังหวะที่ค่อย ๆ ไหล เช่น กลองสด; ค่าน้อยตามละเอียดแต่มีเส้นมาก
        Beat model ใช้โมเดลฟังตำแหน่งบีตโดยตรง เหมาะเพลงซับซ้อนที่ Normal เลือกกริดไม่ตรง ต้องฟังเทียบก่อน Apply

        Shift และ BPM nudge
        Shift ย้ายเส้นที่เลือกทีละ ms หรือเศษบีต เช่น ทั้งท่อนช้าไป 5 ms แต่ระยะบีตถูกแล้ว
        BPM nudge คงจุดเริ่มแล้วเพิ่ม/ลด BPM ทีละขั้น เช่น ต้นท่อนตรงแต่ท้ายท่อนค่อย ๆ หลุด ให้ปรับ 0.01 หรือ 0.001

        Workspace (F3): ฟังซ้ำและจุด A–B
        Shift+ลากเลือกช่วง เปิด Loop แล้ว Play range; Pre-roll 4 เล่นนำหนึ่งห้องก่อนต้นช่วง เพื่อจับจังหวะเข้า
        สลับ speed เพื่อฟังที่ 1.0 กับ 0.75; กด Alt+M ค้างเพื่อฟังดนตรีโดยไม่มี metronome แล้วปล่อยกลับ
        Tap BPM ใช้เคาะตามเพลงเพื่อประมาณ BPM ไม่ใช่คำตอบสุดท้าย กด Auto-time ต่อเพื่อหา offset
        ปัก A กับ B บนสองบีตที่รู้แน่ กรอกจำนวนบีต เช่น 16 ถ้าห่างกันสี่ห้อง 4/4 แล้ว Apply A–B จะคง timing หลัง B

        Workspace: ภาพและทบทวน
        Low ช่วยมอง kick, Mid/High ช่วยมอง snare/เสียงแหลม; Onsets แสดงแรงโจมตีเสียง ส่วน Spectrogram แสดงความถี่ตามเวลา
        SV lane แสดงเส้นเขียว, แถบ Kiai แสดงช่วงที่เปิด Kiai; overview คลิกไปส่วนอื่นได้ ลากปุ่มกลางเพื่อเลื่อน waveform
        Measure view แสดงสี่แถว แถวละสี่ห้อง โดยนับเส้นห้องจริงข้ามการเปลี่ยน BPM/meter และข้ามเส้นที่ omit bar line ใช้ดูโครงสร้างท่อนยาว
        Review แสดง ghost และรายการเส้นที่เสนอ กด A ฟังกริดเดิม / B ฟังข้อเสนอ โดยยังไม่แก้แมพ; Apply ถึงจะบันทึกลงชุดเส้น
        BPM candidates เป็นความแรงสัมพัทธ์ของ autocorrelation ไม่ใช่โอกาสถูก เลือกหนึ่งค่าแล้ว Auto-time หา offset ใหม่
        หลัง Check sections ใช้ Previous/Next issue ไปฟังแต่ละข้อ และ Mark reviewed เมื่อเช็กแล้ว

        บันทึกและส่งออก
        Save .osu บันทึก timing และเก็บ backup ต้นฉบับของ session ไว้ ไม่เขียนทับ backup ทุกครั้ง
        Save project (.tmap) เก็บข้อเสนอที่ยังไม่ Apply, bookmark, ช่วงและมุมมอง เพื่อกลับมาทำต่อ; ไฟล์เสียงอ้างอิงแบบ relative เมื่อทำได้
        โปรแกรมเก็บ recovery แยกและถามก่อนทิ้งงานที่ยังไม่เซฟ เมื่อกู้คืนต้องตรวจแล้วเซฟงานตามปกติ
        Export .osz รวม difficulty ปัจจุบัน เสียงต้นฉบับและสื่อในโฟลเดอร์ โดยไม่เซฟทับ .osu เดิม
        Convert audio to Ogg เป็นคำสั่งแยก เลือก sample rate และ Vorbis quality ได้ (ค่าเริ่มต้น 6) ต้องมี ffmpeg
        เปิด MP3/WAV/FLAC/Ogg ตามต้นฉบับ ไม่แปลงอัตโนมัติ และ Save ไม่เปลี่ยนไฟล์เสียงของ mapset
        Settings → Keyboard shortcuts / copy profiles ปรับคีย์และการชดเชย clipboard ได้ ค่าเริ่มต้น -33 ms; ไม่มีผลต่อเวลาภายในโปรแกรมหรือ Save
