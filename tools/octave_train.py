"""Octave selector (docs/PHASE1-STATUS.md E36): learns which multiple of the detected BPM a mapper writes, from the
features `timing-eval features` exports for ranked/loved songs. Folds are by song, so no song is in its own test fold.

    python tools/octave_train.py train.csv [eval.csv ...]

Reports, per fold and overall: how often the detected BPM is already the mapper's (keep = 1), how often the model's
pick is, and how many sections the model changes for the worse. A model is only worth wiring in when it is right more
often than keeping the detected BPM AND makes almost no section worse (the user's rule: equal or better).
"""
import csv
import sys
from collections import Counter

import numpy as np
from sklearn.ensemble import HistGradientBoostingClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import GroupKFold

RATIOS = ["0.5", "0.6667", "0.75", "1", "1.3333", "1.5", "2"]


def load(path):
    rows = list(csv.DictReader(open(path, encoding="utf-8")))
    feats = [k for k in rows[0] if k.startswith(("log2_", "fit_", "hits_"))]
    X = np.array([[float(r[k]) for k in feats] for r in rows])
    y = np.array([r["label"] for r in rows])
    groups = np.array([r["song"] for r in rows])
    return rows, feats, X, y, groups


def margin_pick(model, X, threshold):
    """The model's ratio, but keep 1 unless it is at least `threshold` more probable than keeping."""
    proba = model.predict_proba(X)
    classes = list(model.classes_)
    keep = classes.index("1") if "1" in classes else None
    picks = []
    for p in proba:
        best = int(np.argmax(p))
        if keep is not None and classes[best] != "1" and p[best] - p[keep] < threshold:
            picks.append("1")
        else:
            picks.append(classes[best])
    return np.array(picks)


def report(name, y, pick):
    learnable = y != ""
    yl, pl = y[learnable], pick[learnable]
    keep_right = (yl == "1").mean()
    model_right = (pl == yl).mean()
    worse = ((yl == "1") & (pl != "1")).sum()
    better = ((yl != "1") & (pl == yl)).sum()
    print(f"  {name:28} sections {len(yl):5}  keep right {keep_right:.3f}  model right {model_right:.3f}  "
          f"fixed {better:4}  broken {worse:4}  changed {(pl != '1').sum():4}")
    return model_right - keep_right, worse


def main():
    rows, feats, X, y, groups = load(sys.argv[1])
    learnable = y != ""
    print(f"{len(rows)} sections, {learnable.sum()} learnable (a candidate within 1 % of the map's BPM), "
          f"{len(set(groups))} songs; labels {dict(Counter(y[learnable]))}")
    X, y, groups = X[learnable], y[learnable], groups[learnable]
    models = {
        "logistic": lambda: LogisticRegression(max_iter=2000, C=1.0),
        "boosted trees": lambda: HistGradientBoostingClassifier(max_iter=200, learning_rate=0.05, max_leaf_nodes=15, l2_regularization=1.0),
    }
    for name, make in models.items():
        print(f"== {name}, 5 folds by song")
        for threshold in (0.0, 0.2, 0.4, 0.6):
            picks = np.empty(len(y), dtype=object)
            for train, test in GroupKFold(n_splits=5).split(X, y, groups):
                m = make().fit(X[train], y[train])
                picks[test] = margin_pick(m, X[test], threshold)
            report(f"margin {threshold:.1f}", y, picks.astype(str))
    # --export <file.cs>: the logistic model trained on every training song, as C# constants for Core OctaveSelector.
    args = sys.argv[2:]
    if "--export" in args:
        target = args[args.index("--export") + 1]
        args = [a for a in args if a not in ("--export", target)]
        m = LogisticRegression(max_iter=2000, C=1.0).fit(X, y)
        def arr(v): return ", ".join(repr(float(x)) for x in v)
        lines = ["// Generated by tools/octave_train.py --export from the ranked/loved training songs; do not edit by hand.",
                 "namespace TimingAnalyzer.Core;", "", "internal static class OctaveModel", "{",
                 f"    public static readonly double[] Ratios = [{', '.join(c for c in m.classes_)}];",
                 f"    public static readonly string[] Features = [{', '.join(chr(34) + f + chr(34) for f in feats)}];",
                 f"    public static readonly double[] Intercepts = [{arr(m.intercept_)}];",
                 "    public static readonly double[][] Weights =", "    ["]
        lines += [f"        [{arr(row)}]," for row in m.coef_]
        lines += ["    ];", "}", ""]
        with open(target, "w", encoding="utf-8", newline="\r\n") as f:
            f.write("\n".join(lines))
        print(f"exported {len(m.classes_)} classes x {len(feats)} features -> {target}")
    # Held-out evaluation sets: train on all training songs, score each eval csv.
    for path in args:
        erows, efeats, eX, ey, eg = load(path)
        assert efeats == feats
        print(f"== held out: {path} ({len(erows)} sections, {(ey != '').sum()} learnable)")
        for name, make in models.items():
            m = make().fit(X, y)
            for threshold in (0.2, 0.4, 0.6):
                report(f"{name}, margin {threshold:.1f}", ey, margin_pick(m, eX, threshold))


if __name__ == "__main__":
    main()
